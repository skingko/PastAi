import AppKit

public struct PasteboardEntry: Sendable, Hashable {
    public var uti: String
    public var data: Data

    public init(uti: String, data: Data) {
        self.uti = uti
        self.data = data
    }
}

/// An owned copy of everything on the pasteboard, safe to hand to background work.
public struct PasteboardSnapshot: Sendable, Hashable {
    public var items: [[PasteboardEntry]]

    public init(items: [[PasteboardEntry]]) { self.items = items }

    public var allTypes: Set<String> { Set(items.flatMap { $0.map(\.uti) }) }
}

public enum PasteboardTypes {
    public static let fileURL = "public.file-url"
    public static let plainText = "public.utf8-plain-text"
    public static let rtf = "public.rtf"
    public static let html = "public.html"
    public static let url = "public.url"
    public static let png = "public.png"
    public static let tiff = "public.tiff"

    /// Preferred order when a clip carries more than one image encoding.
    public static let images = [
        "public.png", "public.jpeg", "public.heic", "org.webmproject.webp", "com.compuserve.gif", "public.tiff", "public.svg-image",
    ]

    /// Password managers and system tools tag secrets with these. See nspasteboard.org.
    public static let concealed: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "com.agilebits.onepassword",
        "net.antelle.keeweb",
    ]

    public static let transient: Set<String> = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "com.typeit4me.clipping",
    ]

    /// Reading these forces the source app to materialise a promise and may trigger file transfers.
    static let unreadable: Set<String> = [
        "com.apple.NSFilePromiseItemMetaData",
        "com.apple.pasteboard.NSFilePromiseID",
        "com.apple.pasteboard.promised-file-content-type",
        "com.apple.pasteboard.promised-file-url",
        "com.apple.pasteboard.promised-suggested-file-name",
    ]
}

public enum PasteboardReader {
    /// Lazily rendered types can be slow, so reading stops once either budget runs out.
    /// The first type of each item is always read because it is the highest-fidelity one.
    public static func read(
        _ pasteboard: NSPasteboard,
        maxBytes: Int = 256 * 1024 * 1024,
        timeBudget: TimeInterval = 1.5
    ) -> PasteboardSnapshot {
        let started = Date()
        var total = 0
        var items: [[PasteboardEntry]] = []
        for item in pasteboard.pasteboardItems ?? [] {
            var entries: [PasteboardEntry] = []
            let isFileItem = item.types.contains { $0.rawValue == PasteboardTypes.fileURL }
            for type in item.types where !PasteboardTypes.unreadable.contains(type.rawValue) {
                // Finder also offers icons and names for each file; the URL alone identifies it.
                if isFileItem, type.rawValue != PasteboardTypes.fileURL { continue }
                let overBudget = total >= maxBytes || Date().timeIntervalSince(started) > timeBudget
                if overBudget, !entries.isEmpty { break }
                guard let data = item.data(forType: type) else { continue }
                total += data.count
                entries.append(PasteboardEntry(uti: type.rawValue, data: data))
            }
            if !entries.isEmpty { items.append(entries) }
        }
        return PasteboardSnapshot(items: items)
    }
}
